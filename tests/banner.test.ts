import { describe, it, expect } from 'vitest';
import {
  generatedBanner,
  generatedBannerToml,
  hasGeneratedBanner,
  stripGeneratedBanner,
  stripGeneratedBannerToml,
  stripLeadingGeneratedBanner,
  withGeneratedBanner,
  withGeneratedBannerToml,
} from '../src/sync/banner.js';

const SOURCE = 'rules/no-console-log.md';

describe('withGeneratedBanner', () => {
  it('inserts the banner after a frontmatter block, before the body', () => {
    const content = '---\ndescription: No console\nscope: "src/**"\n---\n\n# No console\n\nBody text.\n';

    expect(withGeneratedBanner(content, SOURCE)).toBe(
      '---\ndescription: No console\nscope: "src/**"\n---\n\n' +
        `${generatedBanner(SOURCE)}\n\n` +
        '# No console\n\nBody text.\n',
    );
  });

  it('inserts the banner at the top when there is no frontmatter', () => {
    const content = '# Just a heading\n\nBody.\n';

    expect(withGeneratedBanner(content, SOURCE)).toBe(
      `${generatedBanner(SOURCE)}\n\n# Just a heading\n\nBody.\n`,
    );
  });

  it('names the source it was generated from', () => {
    expect(withGeneratedBanner('# x\n', 'skills/my-skill/SKILL.md')).toContain(
      'from skills/my-skill/SKILL.md',
    );
  });

  it('is idempotent — re-running sync never stacks banners', () => {
    const content = '---\nname: agent\n---\n\n# Agent\n';
    const once = withGeneratedBanner(content, SOURCE);
    const twice = withGeneratedBanner(once, SOURCE);

    expect(twice).toBe(once);
    expect(twice.match(/Generated by bluetemberg/g)).toHaveLength(1);
  });

  it('replaces a stale banner rather than appending a second one', () => {
    const stale = withGeneratedBanner('---\nname: agent\n---\n\n# Agent\n', 'agents/old-name.md');
    const fresh = withGeneratedBanner(stale, 'agents/new-name.md');

    expect(fresh).toContain('from agents/new-name.md');
    expect(fresh).not.toContain('from agents/old-name.md');
    expect(fresh.match(/Generated by bluetemberg/g)).toHaveLength(1);
  });

  it('leaves body content untouched, including --- separators inside the body', () => {
    const content = '---\nname: x\n---\n\n# Title\n\n---\n\nAfter a horizontal rule.\n';

    expect(withGeneratedBanner(content, SOURCE)).toContain('# Title\n\n---\n\nAfter a horizontal rule.\n');
  });

  it('treats an unterminated frontmatter fence as no frontmatter', () => {
    const content = '---\nname: never closed\n';

    expect(withGeneratedBanner(content, SOURCE)).toBe(`${generatedBanner(SOURCE)}\n\n${content}`);
  });
});

describe('stripGeneratedBanner', () => {
  it('restores the exact pre-banner content', () => {
    const content = '---\nname: agent\n---\n\n# Agent\n';

    expect(stripGeneratedBanner(withGeneratedBanner(content, SOURCE))).toBe(content);
  });

  it('is a no-op on content that has no banner', () => {
    const content = '# Nothing generated here\n';

    expect(stripGeneratedBanner(content)).toBe(content);
  });
});

describe('withGeneratedBannerToml', () => {
  it('prepends a # comment banner naming the source', () => {
    const out = withGeneratedBannerToml('name = "x"\n', 'agents/x.md');
    expect(out).toBe(`${generatedBannerToml('agents/x.md')}\n\nname = "x"\n`);
    expect(out.startsWith('# Generated by bluetemberg from agents/x.md.')).toBe(true);
  });

  it('is idempotent', () => {
    const once = withGeneratedBannerToml('name = "x"\n', 'agents/x.md');
    expect(withGeneratedBannerToml(once, 'agents/x.md')).toBe(once);
  });
});

describe('hasGeneratedBanner', () => {
  it('recognizes the markdown form, after frontmatter or at the top', () => {
    expect(hasGeneratedBanner(withGeneratedBanner('---\na: 1\n---\n\n# T\n', SOURCE))).toBe(true);
    expect(hasGeneratedBanner(withGeneratedBanner('# T\n', SOURCE))).toBe(true);
  });

  it('recognizes the TOML form', () => {
    expect(hasGeneratedBanner(withGeneratedBannerToml('name = "x"\n', 'agents/x.md'))).toBe(true);
  });

  it('is false for hand-written content, even in a managed directory', () => {
    expect(hasGeneratedBanner('---\ndescription: mine\n---\n\n# Mine\n')).toBe(false);
    expect(hasGeneratedBanner('name = "mine"\n')).toBe(false);
    expect(hasGeneratedBanner('')).toBe(false);
  });
});

describe('stripGeneratedBannerToml', () => {
  it('restores the pre-banner TOML exactly', () => {
    const toml = 'name = "a"\n';
    expect(stripGeneratedBannerToml(withGeneratedBannerToml(toml, 'agents/a.md'))).toBe(toml);
  });

  it('leaves unbannered content alone', () => {
    expect(stripGeneratedBannerToml('# a comment\nname = "a"\n')).toBe('# a comment\nname = "a"\n');
  });
});

describe('stripLeadingGeneratedBanner', () => {
  it('strips the banner where the emitters put it, with or without frontmatter', () => {
    const body = '# Rule\n';
    const fm = '---\ndescription: d\n---\n';
    expect(stripLeadingGeneratedBanner(withGeneratedBanner(body, SOURCE))).toBe(body);
    expect(stripLeadingGeneratedBanner(withGeneratedBanner(fm + body, SOURCE))).toBe(`${fm}\n${body}`);
    expect(stripLeadingGeneratedBanner(withGeneratedBannerToml('name = "a"\n', SOURCE))).toBe('name = "a"\n');
  });

  it('leaves a banner that is quoted below the start of the body', () => {
    const doc = `# Docs\n\n${generatedBanner(SOURCE)}\n`;
    expect(stripLeadingGeneratedBanner(doc)).toBe(doc);
  });

  it('handles CRLF line endings', () => {
    const crlf = withGeneratedBanner('---\nd: 1\n---\n# R\n', SOURCE).replace(/\n/g, '\r\n');
    expect(stripLeadingGeneratedBanner(crlf)).toBe('---\r\nd: 1\r\n---\r\n\r\n# R\r\n');
  });
});
