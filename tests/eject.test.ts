import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parse as tomlParse } from 'smol-toml';
import { sync } from '../src/sync/index.js';
import { eject } from '../src/eject/index.js';

const GUARDRAIL = `---
description: Branch names
trigger: EnterWorktree
check:
  field: name
  not_empty: true
  not_matches: '^claude/'
message: 'Use type/description.'
---

# Branch names
`;

const NO_FORCE_PUSH = `---
description: No force push
trigger: Bash
check:
  field: command
  not_matches: 'git push.*--force'
message: 'Force-push is blocked.'
---

# No force push
`;

const BANNER_LINE = /^(<!-- |# )Generated by bluetemberg.*\n(\n)?/m;

function write(root: string, rel: string, content: string): void {
  mkdirSync(join(root, rel, '..'), { recursive: true });
  writeFileSync(join(root, rel), content);
}

function read(root: string, rel: string): string {
  return readFileSync(join(root, rel), 'utf8');
}

function json(root: string, rel: string): Record<string, unknown> {
  return JSON.parse(read(root, rel)) as Record<string, unknown>;
}

/** Every file under `root` except `.git`, relative to it. */
function files(root: string, rel = ''): string[] {
  return readdirSync(join(root, rel), { withFileTypes: true }).flatMap((ent) => {
    const child = rel ? join(rel, ent.name) : ent.name;
    return ent.isDirectory() ? files(root, child) : [child];
  });
}

/** A synced project across several platforms, plus files a person wrote. */
async function syncedProject(root: string): Promise<void> {
  write(
    root,
    'bluetemberg.config.json',
    JSON.stringify({
      platforms: ['cursor', 'claude', 'copilot', 'gemini', 'codex', 'claude-marketplace'],
      source: 'llm',
      marketplace: { remote: 'acme/mkt', plugins: [{ name: 'core', displayName: 'Core' }] },
    }),
  );
  write(root, 'llm/rules/r.md', '---\ndescription: d\nscope: "**"\n---\n# R\nbody\n');
  write(root, 'llm/agents/a.md', '---\nname: a\ndescription: An agent\n---\nDo agent things.\n');
  write(root, 'llm/guardrails/branch.md', GUARDRAIL);
  write(root, 'llm/guardrails/no-force-push.md', NO_FORCE_PUSH);
  write(root, 'llm/mcp.json', JSON.stringify({ servers: ['context7'] }));
  write(root, 'llm/packages.json', JSON.stringify({ packages: {} }));
  write(root, 'AGENTS.md', '# Project\n\nWritten by a person.\n');
  write(root, 'docs/notes.md', '# Notes\n\nMine.\n');
  write(root, '.mcp.json', JSON.stringify({ mcpServers: { mine: { command: 'my-server' } } }));
  write(root, '.claude/settings.json', JSON.stringify({ permissions: { allow: ['Bash(ls)'] } }));
  write(
    root,
    '.gitignore',
    'dist/\n\n# Bluetemberg cache\n.bluetemberg/\n\n# Registry credentials\n.npmrc\n',
  );
  write(root, '.bluetemberg/catalog.json', '{}');
  const results = await sync(root, { silent: true, recursive: false });
  expect(results.errors).toEqual([]);
}

describe('eject', () => {
  let root: string;
  let logSpy: ReturnType<typeof vi.spyOn>;

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'bt-eject-'));
    logSpy = vi.spyOn(console, 'log').mockImplementation(() => {});
  });

  afterEach(() => {
    rmSync(root, { recursive: true, force: true });
    logSpy.mockRestore();
  });

  it('refuses a directory without bluetemberg.config.json', async () => {
    await expect(eject(root)).rejects.toThrow('nothing to eject');
  });

  it('dry run reports the plan and changes nothing', async () => {
    await syncedProject(root);
    const before = new Map(files(root).map((f) => [f, read(root, f)]));

    const plan = await eject(root, { dryRun: true });

    expect(plan.removed).toEqual(
      expect.arrayContaining(['bluetemberg.config.json', 'llm/mcp-managed.json', 'llm/packages.json']),
    );
    expect(plan.edited).toEqual(expect.arrayContaining(['.claude/rules/r.md', 'AGENTS.md']));
    expect(new Map(files(root).map((f) => [f, read(root, f)]))).toEqual(before);
  });

  it('strips banners and leaves the generated content otherwise byte-identical', async () => {
    await syncedProject(root);
    const bannered = [
      '.claude/rules/r.md',
      '.cursor/rules/r.mdc',
      '.claude/agents/a.md',
      '.codex/agents/a.toml',
      '.github/copilot-instructions.md',
    ];
    const generated = new Map(bannered.map((f) => [f, read(root, f)]));

    await eject(root);

    for (const [file, content] of generated) {
      expect(content, file).toMatch(BANNER_LINE);
      expect(read(root, file), file).toBe(content.replace(BANNER_LINE, ''));
    }
    for (const file of files(root)) {
      expect(read(root, file), file).not.toContain('Generated by bluetemberg');
    }
  });

  it('removes managed-block markers and keeps their content', async () => {
    await syncedProject(root);
    const codexBefore = read(root, '.codex/config.toml');

    await eject(root);

    const agents = read(root, 'AGENTS.md');
    expect(agents).not.toContain('BLUETEMBERG MANAGED');
    expect(agents).toMatch(/^# Project\n\nWritten by a person\.\n\n/);
    expect(agents).toContain('# R\nbody');

    const codex = read(root, '.codex/config.toml');
    expect(codex).not.toContain('BLUETEMBERG MANAGED');
    expect(tomlParse(codex)).toEqual(tomlParse(codexBefore));
    expect(codex).toContain('[mcp_servers.context7]');
    expect(codex).toContain('[[hooks.PreToolUse]]');
  });

  it('removes bluetemberg state and keeps user files and managed JSON entries', async () => {
    await syncedProject(root);
    const settings = json(root, '.claude/settings.json');
    const mcp = json(root, '.mcp.json');
    const gemini = json(root, '.gemini/settings.json');

    const result = await eject(root);

    for (const gone of [
      'bluetemberg.config.json',
      '.bluetemberg',
      'llm/mcp-managed.json',
      'llm/mcp.json',
      'llm/packages.json',
    ]) {
      expect(existsSync(join(root, gone)), gone).toBe(false);
    }
    expect(result.removed).toContain('bluetemberg.config.json');
    expect(read(root, 'llm/rules/r.md')).toBe('---\ndescription: d\nscope: "**"\n---\n# R\nbody\n');
    expect(read(root, 'llm/guardrails/branch.md')).toBe(GUARDRAIL);
    expect(read(root, 'docs/notes.md')).toBe('# Notes\n\nMine.\n');
    expect(json(root, '.claude/settings.json')).toEqual(settings);
    expect(json(root, '.mcp.json')).toEqual(mcp);
    expect(json(root, '.gemini/settings.json')).toEqual(gemini);
    expect(JSON.stringify(settings)).toContain('bash -c');
    expect(existsSync(join(root, '.claude-plugin/marketplace.json'))).toBe(true);
  });

  it('drops the cache ignore entry but keeps the .npmrc guard', async () => {
    await syncedProject(root);

    await eject(root);

    const gitignore = read(root, '.gitignore');
    expect(gitignore).not.toContain('.bluetemberg/');
    expect(gitignore).toContain('.npmrc');
    expect(gitignore).toContain('dist/');
  });

  it('aborts with nothing changed when a managed block is malformed', async () => {
    await syncedProject(root);
    write(root, 'AGENTS.md', `${read(root, 'AGENTS.md')}\n<!-- END BLUETEMBERG MANAGED RULES -->\n`);
    const before = new Map(files(root).map((f) => [f, read(root, f)]));

    await expect(eject(root)).rejects.toThrow('malformed managed block');
    expect(new Map(files(root).map((f) => [f, read(root, f)]))).toEqual(before);
  });
});
