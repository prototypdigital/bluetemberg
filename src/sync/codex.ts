// Codex has no per-file rule API; see Architecture.md "Special sync" for the full design.
export interface CodexSyncContext extends SyncSink {
  sourceBase: string;
  sourceDirs: string[];
  platforms: readonly Platform[];
  /** Rules the version gate withheld (`file → reason`); left out of the AGENTS.md block. */
  excludedRules?: ReadonlyMap<string, string>;
  /** Agents the version gate withheld (`file → reason`); no `.codex/agents/*.toml` is written for them. */
  excludedAgents?: ReadonlyMap<string, string>;
}

/** Stable filename ordering so generated output is deterministic across runs. */
function byFilename(a: [string, string], b: [string, string]): number {
  return a[0].localeCompare(b[0]);
}

/** Renders a scope annotation line, or empty for global (`**`) / unscoped rules. */
function scopeAnnotation(scope: string | string[] | undefined): string {
  if (scope === undefined) return '';
  const globs = Array.isArray(scope) ? scope : [scope];
  const meaningful = globs.filter((g) => g && g !== '**');
  if (meaningful.length === 0) return '';
  return `_Applies to: ${meaningful.map((g) => `\`${g}\``).join(', ')}_`;
}

/**
 * Rejects a rule whose body quotes a managed-block marker verbatim.
 *
 * Every rule lands in one shared block, so a single marker in a single body would wedge AGENTS.md
 * for good. Failing here names the rule that has to change; letting it through would only name
 * AGENTS.md, long after the cause.
 */
function assertRuleQuotesNoMarker(file: string, body: string): void {
  for (const marker of [AGENTS_RULES_MARKERS.begin, AGENTS_RULES_MARKERS.end]) {
    if (!body.includes(marker)) continue;
    throw new Error(
      `rules/${file} quotes the managed-block marker \`${marker}\` verbatim, which would wedge the ` +
        'AGENTS.md block on the next sync. Reword the rule so the literal marker does not appear ' +
        '(dropping the comment delimiters is enough).',
    );
  }
}

/** Builds the inner body of the AGENTS.md rules block (empty when there are no rules). */
function buildRulesBlock(ctx: CodexSyncContext): string {
  const merged = mergeSourceFiles(ctx.sourceDirs, 'rules', (f) => f.endsWith('.md'));
  const applied = [...merged].filter(([file]) => !ctx.excludedRules?.has(file));
  if (applied.length === 0) return '';

  const sections: string[] = [
    'Generated by bluetemberg from `llm/rules/`. Do not edit between the markers — run `bluetemberg sync`.',
  ];

  for (const [file, sourceDir] of applied.sort(byFilename)) {
    const parsed = matter.read(join(sourceDir, file));
    const scope = parsed.data.scope as string | string[] | undefined;
    const section = [scopeAnnotation(scope), parsed.content.trim()].filter(Boolean).join('\n\n');
    assertRuleQuotesNoMarker(file, section);
    sections.push(section);
  }

  return sections.join('\n\n');
}

function getSafeRulesBlock(ctx: CodexSyncContext, recordError: (message: string) => void): string | null {
  try {
    return buildRulesBlock(ctx);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    recordError(`codex rules -> AGENTS.md: ${message}`);
    return null;
  }
}

/**
 * Injects the block, or records a diagnostic and returns `null` when the target file's markers are
 * malformed. Skipping (rather than guessing) keeps a hand-broken block from growing on every run;
 * the recorded error names the file and fails `sync` / `sync --check`.
 */
function injectOrRecord(
  ctx: CodexSyncContext,
  filePath: string,
  existing: string | null,
  inner: string,
  markers: BlockMarkers,
  recordError: (message: string) => void,
): string | null {
  try {
    return injectManagedBlock(existing, inner, markers, relative(ctx.root, filePath));
  } catch (err) {
    // Anything that is not a marker problem is a bug in here, not bad input — let it surface.
    if (!(err instanceof ManagedBlockError)) throw err;
    recordError(err.message);
    return null;
  }
}

/** True when the file exists and carries either marker — a block, or the wreckage of one. */
function hasAnyMarker(existing: string | null, markers: BlockMarkers): boolean {
  if (existing === null) return false;
  return existing.includes(markers.begin) || existing.includes(markers.end);
}

/**
 * Platforms with no per-path rule API: they read `AGENTS.md` and nothing else, so the managed rules
 * block is the only place their rules can go.
 */
export const AGENTS_MD_RULE_PLATFORMS: readonly Platform[] = ['codex', 'gemini'];

/**
 * Folds `llm/rules/` into a managed block in the root `AGENTS.md`, preserving hand-authored content.
 */
export function syncCodexRules(ctx: CodexSyncContext, recordError: (message: string) => void): void {
  if (!AGENTS_MD_RULE_PLATFORMS.some((p) => ctx.platforms.includes(p))) return;

  const agentsPath = join(ctx.root, 'AGENTS.md');
  const existing = readIfExists(agentsPath);

  const block = getSafeRulesBlock(ctx, recordError);
  if (block === null) return;

  if (block.length === 0 && !hasAnyMarker(existing, AGENTS_RULES_MARKERS)) return;

  const output = injectOrRecord(ctx, agentsPath, existing, block, AGENTS_RULES_MARKERS, recordError);
  if (output === null) return;
  if (output.length === 0 && existing === null) return;

  commitPlannedWrite(ctx, agentsPath, output);
  if (!ctx.checkMode) ctx.log('Rules: merged into AGENTS.md');
}

function processAgentFile(
  file: string,
  sourceDir: string,
  outDir: string,
  ctx: CodexSyncContext,
  recordError: (message: string) => void,
): boolean {
  try {
    const parsed = matter.read(join(sourceDir, file));
    const fallbackName = basename(file, '.md');
    const name =
      typeof parsed.data.name === 'string' && parsed.data.name.trim().length > 0
        ? parsed.data.name.trim()
        : fallbackName;

    const agent: Record<string, unknown> = {
      name,
      description: typeof parsed.data.description === 'string' ? parsed.data.description : '',
      developer_instructions: parsed.content.trim(),
    };

    const body = withGeneratedBannerToml(tomlStringify(agent) + '\n', `agents/${file}`);
    commitPlannedWrite(ctx, join(outDir, `${fallbackName}.toml`), body);
    return true;
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    recordError(`codex agent ${file}: ${message}`);
    return false;
  }
}

/** Emits one `.codex/agents/<name>.toml` per source agent, mapping the body to `developer_instructions`. */
export function syncCodexAgents(ctx: CodexSyncContext, recordError: (message: string) => void): void {
  if (!ctx.platforms.includes('codex')) return;

  const merged = mergeSourceFiles(ctx.sourceDirs, 'agents', (f) => f.endsWith('.md') && f !== 'README.md');
  if (merged.size === 0) return;

  const outDir = join(ctx.root, '.codex', 'agents');

  const count = [...merged]
    .filter(([file]) => !ctx.excludedAgents?.has(file))
    .sort(byFilename)
    .filter(([file, sourceDir]) => processAgentFile(file, sourceDir, outDir, ctx, recordError)).length;

  if (count > 0 && !ctx.checkMode) ctx.log(`Codex agents: ${count} -> .codex/agents/`);
}

/** Maps our internal MCP shape to Codex's TOML shape (stdio = command/args, HTTP = url). */
function toCodexMcpServers(
  configs: Record<string, McpServerConfig>,
): Record<string, Record<string, unknown>> {
  const out: Record<string, Record<string, unknown>> = {};
  for (const [id, cfg] of Object.entries(configs)) {
    const entry: Record<string, unknown> = {};
    if (cfg.url) {
      entry.url = cfg.url;
    } else if (cfg.command) {
      entry.command = cfg.command;
      if (cfg.args && cfg.args.length > 0) entry.args = cfg.args;
    }
    // Skip entries with no transport — neither url nor command were set.
    if (Object.keys(entry).length > 0) out[id] = entry;
  }
  return out;
}

/**
 * The managed block's body, `''` for no servers, or `null` to leave the file alone. An unreadable
 * manifest is `null` (its error is already recorded by `syncMcp`), so a typo never clears the block.
 */
function buildMcpInner(sourceBase: string, recordError: (message: string) => void): string | null {
  const manifest = loadMcpManifest(sourceBase);
  if (manifest.status === 'invalid') return null;
  try {
    const servers = toCodexMcpServers(manifest.status === 'ok' ? manifest.configs : {});
    return Object.keys(servers).length > 0 ? tomlStringify({ mcp_servers: servers }).trim() : '';
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    recordError(`codex mcp -> .codex/config.toml: ${message}`);
    return null;
  }
}

/** File content after one managed block is applied, and whether the block touched the file at all. */
interface BlockStep {
  content: string | null;
  touched: boolean;
}

/**
 * Applies one managed block to `current`. `inner` of `null` leaves the file alone (its source could
 * not be read), and an empty `inner` only matters when an earlier sync left markers to clear.
 */
function applyBlock(
  ctx: CodexSyncContext,
  filePath: string,
  current: string | null,
  inner: string | null,
  markers: BlockMarkers,
  recordError: (message: string) => void,
): BlockStep {
  const untouched = { content: current, touched: false };
  if (inner === null) return untouched;
  if (inner.length === 0 && !hasAnyMarker(current, markers)) return untouched;

  const output = injectOrRecord(ctx, filePath, current, inner, markers, recordError);
  if (output === null) return untouched;
  if (output.length === 0 && current === null) return untouched;
  return { content: output, touched: true };
}

function warn(ctx: CodexSyncContext, msg: string): void {
  ctx.results.warnings.push(msg);
  ctx.log(`  WARN: ${msg}`);
}

/**
 * True when `root` sits in a linked git worktree: the nearest `.git` above it is a file pointing at
 * the main repository, not a directory. Codex replaces such a checkout's `hooks` with the main
 * checkout's (`merge_root_checkout_project_hooks`).
 */
function isLinkedWorktree(root: string): boolean {
  for (let dir = resolve(root); ; dir = dirname(dir)) {
    const dotGit = join(dir, '.git');
    if (existsSync(dotGit)) return statSync(dotGit).isFile();
    if (dirname(dir) === dir) return false;
  }
}

function isValidToml(content: string | null): boolean {
  if (content === null) return true;
  try {
    tomlParse(content);
    return true;
  } catch {
    return false;
  }
}

/**
 * Applies the guardrail hooks block, keeping the file as it was when the result would not be valid
 * TOML. That happens when hand-written config already defines `hooks.PreToolUse` as a plain array or
 * inline table, which `[[hooks.PreToolUse]]` cannot extend; writing it anyway would break the whole
 * file for Codex, not just the hooks.
 */
function applyHooksBlock(
  ctx: CodexSyncContext,
  filePath: string,
  current: string | null,
  inner: string,
  recordError: (message: string) => void,
): BlockStep {
  const step = applyBlock(ctx, filePath, current, inner, CODEX_HOOKS_MARKERS, recordError);
  if (!step.touched || inner.length === 0 || step.content === null) return step;

  let parsed: Record<string, unknown>;
  try {
    parsed = tomlParse(step.content);
  } catch (err) {
    const detail = err instanceof Error ? err.message.split('\n')[0] : String(err);
    const cause = isValidToml(current)
      ? `adding the guardrail hooks block would leave invalid TOML (${detail}); move hand-written hooks to [[hooks.PreToolUse]] tables or .codex/hooks.json`
      : `the file is not valid TOML (${detail}); fix it`;
    recordError(`.codex/config.toml: ${cause}. The Codex guardrail hooks were not written.`);
    return { content: current, touched: false };
  }
  if (codexHooksDisabled(parsed)) {
    warn(
      ctx,
      '.codex/config.toml turns hooks off ([features] hooks = false), so Codex will not run the guardrail hooks',
    );
  }
  if (isLinkedWorktree(ctx.root)) {
    warn(
      ctx,
      '.codex/config.toml is in a linked git worktree. Codex reads project hooks from the main checkout, so these ' +
        'guardrail hooks run only once the main checkout is synced with them',
    );
  }
  return step;
}

/**
 * Single writer of `.codex/config.toml`: injects the managed `[mcp_servers.*]` block and the managed
 * guardrail `[[hooks.PreToolUse]]` block, preserving hand-authored config around them. Both blocks go
 * in one pass so `--check` compares one planned file, not two that each miss the other's change. A
 * file that ends up empty (it only ever held managed blocks) is removed.
 */
export function syncCodexConfig(
  ctx: CodexSyncContext,
  guardrailHooks: CodexHooksSection | null,
  recordError: (message: string) => void,
): void {
  if (!ctx.platforms.includes('codex')) return;

  const configPath = join(ctx.root, '.codex', 'config.toml');
  const existing = readIfExists(configPath);

  const mcp = applyBlock(
    ctx,
    configPath,
    existing,
    buildMcpInner(ctx.sourceBase, recordError),
    CODEX_MCP_MARKERS,
    recordError,
  );
  const hooks = applyHooksBlock(
    ctx,
    configPath,
    mcp.content,
    renderCodexHooksBlock(guardrailHooks),
    recordError,
  );
  if (!mcp.touched && !hooks.touched) return;

  const output = hooks.content ?? '';
  if (output.length === 0) {
    commitPlannedDelete(ctx, configPath);
  } else {
    commitPlannedWrite(ctx, configPath, output);
  }
  if (!ctx.checkMode && mcp.touched) ctx.log('Codex MCP: merged into .codex/config.toml');
}
