interface PacksTree {
  /** Every path under `packages/` on the base ref. */
  paths: Set<string>;
  /** Pack dir names on the base ref. */
  packs: string[];
}

function packsTree(git: GitRunner, repo: string): PacksTree {
  const listing = git(['ls-tree', '-r', '--name-only', BASE_REF, '--', 'packages'], repo);
  const paths = new Set(listing.split('\n').filter(Boolean));
  const packs = [
    ...new Set([...paths].map((p) => p.split('/')[1]).filter((p): p is string => Boolean(p))),
  ].sort();
  return { paths, packs };
}

function packStacks(git: GitRunner, repo: string, pack: string): string[] {
  try {
    const manifest: unknown = JSON.parse(git(['show', `${BASE_REF}:packages/${pack}/package.json`], repo));
    const meta = isPlainObject(manifest) && isPlainObject(manifest.bluetemberg) ? manifest.bluetemberg : {};
    return Array.isArray(meta.stacks) ? meta.stacks.filter((s): s is string => typeof s === 'string') : [];
  } catch {
    return [];
  }
}

/** `bluetemberg-rules-*` holds rules, `bluetemberg-skills-*` skills, `bluetemberg-agents-*` agents. */
function packPrefix(kind: DraftKind): string {
  return `bluetemberg-${kind}s-`;
}

function pickPack(
  git: GitRunner,
  repo: string,
  tree: PacksTree,
  archive: Archive,
  requested?: string,
): string {
  const prefix = packPrefix(archive.kind);
  if (requested !== undefined) {
    if (!tree.packs.includes(requested))
      throw new Error(`no pack "${requested}" on ${BASE_REF} in the packs repo`);
    if (!requested.startsWith(prefix))
      throw new Error(`"${requested}" is not a ${archive.kind} pack (${prefix}*)`);
    return requested;
  }
  const candidates = tree.packs.filter(
    (p) => p.startsWith(prefix) && packStacks(git, repo, p).includes(archive.gap.stack),
  );
  if (candidates.length === 1) return candidates[0];
  if (candidates.length === 0) {
    throw new Error(
      `no ${archive.kind} pack declares the stack "${archive.gap.stack}" — create one (create-pack skill), then pass --pack`,
    );
  }
  throw new Error(
    `several ${archive.kind} packs declare "${archive.gap.stack}" (${candidates.join(', ')}) — pass --pack`,
  );
}

/** The path a new item takes inside a pack, `/`-separated, relative to the packs repo. */
function packItemPath(pack: string, kind: DraftKind, name: string): { file: string; taken: string } {
  const target = kindTarget(['packages', pack, 'llm'].join('/'), kind, name);
  const toPosix = (p: string): string => p.split(sep).join('/');
  return { file: toPosix(target.file), taken: toPosix(target.dir ?? target.file) };
}

/** Refuse a name another pack already uses for the same kind: it would shadow or be shadowed. */
function assertNameFree(tree: PacksTree, kind: DraftKind, name: string): void {
  const clash = tree.packs.find((pack) => {
    const { taken } = packItemPath(pack, kind, name);
    return [...tree.paths].some((p) => p === taken || p.startsWith(`${taken}/`));
  });
  if (clash) throw new Error(`a ${kind} named "${name}" already exists in ${clash} on ${BASE_REF}`);
}

function assertPacksRepo(git: GitRunner, repo: string): void {
  if (!existsSync(join(repo, 'catalog.json')) || !existsSync(join(repo, 'packages'))) {
    throw new Error(`${repo} is not a bluetemberg-packs checkout (no catalog.json and packages/)`);
  }
  const top = git(['rev-parse', '--show-toplevel'], repo).trim();
  // git reports the real path (macOS /var → /private/var, case-folded names), so compare real paths.
  if (realpathSync.native(top) !== realpathSync.native(repo)) {
    throw new Error(`pass the packs repo root (${top}), not a subdirectory (${repo})`);
  }
  if (git(['status', '--porcelain'], repo).trim() !== '') {
    throw new Error('the packs checkout has uncommitted changes — commit or stash them first');
  }
}

function branchExists(git: GitRunner, repo: string, branch: string): boolean {
  try {
    git(['rev-parse', '--verify', '--quiet', `refs/heads/${branch}`], repo);
    return true;
  } catch {
    return false;
  }
}

