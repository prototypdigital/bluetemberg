// PR text — every draft-derived value is untrusted and rendered inert
// ---------------------------------------------------------------------------

/** One-line `code` span that no content can break out of; GitHub does not link @mentions in code. */
export function codeSpan(value: string): string {
  const text = sanitizeForTerminal(value).replace(/[\r\n]+/g, ' ');
  const longest = Math.max(0, ...(text.match(/`+/g) ?? []).map((run) => run.length));
  const fence = '`'.repeat(longest + 1);
  return `${fence} ${text} ${fence}`;
}

function fencedBlock(value: string): string {
  const text = sanitizeForTerminal(value);
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((run) => run.length));
  const fence = '`'.repeat(longest + 1);
  return `${fence}text\n${text}\n${fence}`;
}

function citationLines(archive: Archive): string[] {
  return archive.citations.flatMap((c, i) => {
    const href = new URL(c.url).href;
    return [`${i + 1}. <${href}> — retrieved ${codeSpan(c.retrieved)}`, '', fencedBlock(c.quote), ''];
  });
}

function prTitle(archive: Archive, name: string, range: string): string {
  return `feat(packs): add ${name} ${archive.kind} for ${archive.gap.stack} ${range}`;
}

function prBody(archive: Archive, pack: string, edited: boolean, range: string): string {
  return [
    'Drafted with the bluetemberg create-loop ([#197](https://github.com/prototypdigital/bluetemberg/issues/197)) and promoted by a human reviewer. **A maintainer must verify it against the cited docs before merge.**',
    '',
    '| | |',
    '| --- | --- |',
    `| Kind | ${archive.kind} |`,
    `| Pack | ${codeSpan(pack)} |`,
    `| Fills gap | ${codeSpan(`${archive.gap.stack}@${archive.gap.version}`)} (${codeSpan(archive.gap.reason)}), range ${codeSpan(range)} |`,
    `| Reviewed by | ${codeSpan(archive.reviewedBy)} at ${codeSpan(archive.reviewedAt)} |`,
    `| Reviewed draft sha256 | ${codeSpan(archive.sha256)} |`,
    `| Citations verified at promote | ${archive.citationsVerified ? 'yes' : '**no** (skipped)'} |`,
    `| Edited after review | ${edited ? '**yes** — the contributed file differs from the reviewed draft' : 'no'} |`,
    `| Engine | ${codeSpan(archive.engine)} |`,
    '',
    '### Citations',
    '',
    ...citationLines(archive),
    '### Checklist',
    '',
    '- [ ] `npm run generate:catalog` was run and `catalog.json` committed',
    '- [ ] Content verified against the cited documentation',
    '- [ ] Range bounded to the majors it was checked against (`bluetemberg stacks lint`)',
    '',
  ].join('\n');
}

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function nextSteps(repo: string, branch: string, title: string, bodyFile: string): string[] {
  return [
    `cd ${shellQuote(repo)}`,
    'npm run generate:catalog',
    'git add catalog.json',
    `git commit -m ${shellQuote(title)}`,
    `git push -u origin ${shellQuote(branch)}`,
    `gh pr create --draft --base main --head ${shellQuote(branch)} --label ${REVIEW_LABEL} --title ${shellQuote(title)} --body-file ${shellQuote(bodyFile)}`,
  ];
}

