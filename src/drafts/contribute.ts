/**
 * `bluetemberg draft pr` — turn a promoted draft into a contribution branch in a local
 * bluetemberg-packs checkout (M7 phase 3, #197).
 *
 * The engine does the mechanical, checkable part and stops: it re-checks the promoted file, picks
 * the pack from `origin/main`, refuses a name already taken in any pack, creates a branch, writes
 * and stages the file, and writes a provenance-stamped PR body. It never commits, pushes or opens
 * the PR, and never runs the packs repo's own scripts — committing runs that repo's hooks, and the
 * catalog must be regenerated by the packs repo's generator first. Those steps are printed for the
 * human, and the PR they open is a draft labelled `needs-review`.
 */

export const BASE_REF = 'origin/main';
export const REVIEW_LABEL = 'needs-review';
const SHA256 = /^[0-9a-f]{64}$/;
const STACK_NAME = /^[a-z0-9][a-z0-9._-]{0,63}$/;

/** Runs `git` with an argument array (never a shell) in `cwd`; returns stdout. Injectable for tests. */
export type GitRunner = (args: string[], cwd: string) => string;

/**
 * Every git call the engine makes in the packs repo runs with that repo's hooks off and no
 * filesystem monitor: `git switch` would otherwise run a `post-checkout` hook and `git status` a
 * `core.fsmonitor` command — the packs repo's code, run by our command. Its own commit, which runs
 * its hooks, is left to the human.
 */
const NO_REPO_CODE = ['-c', `core.hooksPath=${devNull}`, '-c', 'core.fsmonitor=false'];

export const runGit: GitRunner = (args, cwd) =>
  execFileSync('git', [...NO_REPO_CODE, ...args], {
    cwd,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });

export interface ContributeOptions {
  /** The local bluetemberg-packs checkout. */
  packsRepo: string;
  /** The pack to add to; picked from the gap stack when omitted. */
  pack?: string;
  env?: Record<string, string | undefined>;
  git?: GitRunner;
}

interface Archive {
  kind: DraftKind;
  frontmatter: Record<string, unknown>;
  body: string;
  citations: Citation[];
  gap: { stack: string; version: string; reason: string };
  /** The range the file declares for the gap stack. */
  range: string;
  reviewedBy: string;
  reviewedAt: string;
  sha256: string;
  citationsVerified: boolean;
  engine: string;
}

export interface ContributionResult {
  pack: string;
  branch: string;
  /** The file written and staged, relative to the packs repo. */
  file: string;
  /** The PR body, relative to the project root. */
  bodyFile: string;
  title: string;
  /** The promoted file differs from what the reviewer approved. */
  editedAfterReview: boolean;
  /** The commands the human runs next, in order. */
  nextSteps: string[];
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function str(value: unknown): string | null {
  return typeof value === 'string' && value.trim() !== '' ? value : null;
}

function readCapped(path: string, label: string): string {
  const stat = lstatSync(path, { throwIfNoEntry: false });
  if (!stat?.isFile()) throw new Error(`${label} not found (or not a regular file)`);
  if (stat.size > MAX_DRAFT_BYTES) throw new Error(`${label} is larger than ${MAX_DRAFT_BYTES / 1024} KiB`);
  return readFileSync(path, 'utf8');
}

/** The archive's citations. The archive is local and editable, so each URL is re-validated. */
function isCitation(value: unknown): value is Citation {
  return (
    isPlainObject(value) &&
    typeof value.url === 'string' &&
    typeof value.quote === 'string' &&
    typeof value.retrieved === 'string'
  );
}

function citationsOf(raw: unknown, name: string): Citation[] {
  if (!Array.isArray(raw) || raw.length === 0) {
    throw new Error(`the archive for "${name}" records no citations`);
  }
  return raw.map((c: unknown, i) => {
    if (!isCitation(c) || urlIssue(c.url) !== null) {
      throw new Error(`the archive for "${name}" has an invalid citation (#${i + 1})`);
    }
    return { url: c.url, quote: c.quote, retrieved: c.retrieved };
  });
}

/** Read the promoted-draft archive. It must record a human review: reviewer, time and hash. */
function readArchive(root: string, name: string): Archive {
  const path = promotedPath(root, name);
  assertNoSymlinks(root, path);
  const { data, body } = parseStrictFrontmatter(
    readCapped(path, `no promoted draft "${name}" (run \`draft promote\` first)`),
  );
  const draft = data[DRAFT_KEY];
  if (!isPlainObject(draft) || draft.status !== 'promoted') {
    throw new Error(`"${name}" has not been promoted — run \`bluetemberg draft promote ${name}\` first`);
  }
  const gap = isPlainObject(draft.gap) ? draft.gap : {};
  const reviewedBy = str(draft.reviewedBy);
  const reviewedAt = str(draft.reviewedAt);
  const hash = typeof draft.sha256 === 'string' && SHA256.test(draft.sha256) ? draft.sha256 : null;
  const stack = str(gap.stack);
  const version = str(gap.version);
  if (!isDraftKind(draft.kind) || !reviewedBy || !reviewedAt || !hash || !stack || !version) {
    throw new Error(`the archive for "${name}" is incomplete — it does not record a human review`);
  }
  // These reach a commit title and shell commands, so they are held to their real formats.
  const stacks = isPlainObject(data.stacks) ? data.stacks : {};
  const range = stacks[stack];
  if (
    !STACK_NAME.test(stack) ||
    typeof range !== 'string' ||
    !isValidStackRange(range) ||
    isWildcardRange(range)
  ) {
    throw new Error(`the archive for "${name}" has no valid stack range for its gap`);
  }
  const frontmatter = Object.fromEntries(Object.entries(data).filter(([key]) => key !== DRAFT_KEY));
  return {
    kind: draft.kind,
    frontmatter,
    body,
    citations: citationsOf(draft.citations, name),
    gap: { stack, version, reason: str(gap.reason) ?? 'unknown' },
    range,
    reviewedBy,
    reviewedAt,
    sha256: hash,
    citationsVerified: draft.citationsVerified === true,
    engine: str(draft.engine) ?? 'bluetemberg',
  };
}

/**
 * Re-check the promoted file as it is now — a human may have edited it after review, and it is
 * what gets contributed. It must still be the kind's house format with no `draft` key, and pass
 * the same safety checks as a draft.
 */
function readPromoted(root: string, name: string, archive: Archive): { text: string; edited: boolean } {
  const file = kindTarget(join(resolve(root), loadConfig(root).source), archive.kind, name).file;
  assertNoSymlinks(root, file);
  const text = readCapped(file, `the promoted ${archive.kind} ${displayPath(root, file)}`);
  const { data } = parseStrictFrontmatter(text);
  const allowed = new Set(KIND_SPECS[archive.kind].keys);
  const stray = Object.keys(data).filter((k) => !allowed.has(k));
  if (stray.length > 0) {
    throw new Error(
      `${displayPath(root, file)} has keys outside the ${archive.kind} format: ${stray.map((k) => quoteValue(k, 40)).join(', ')}`,
    );
  }
  const issues = safetyIssues(text, name, archive.kind);
  if (issues.length > 0) {
    throw new Error(
      [
        `${displayPath(root, file)} fails the safety checks:`,
        ...issues.map((i) => `  [${i.code}] ${i.message}`),
      ].join('\n'),
    );
  }
  const reviewed = renderPromoted({
    frontmatter: archive.frontmatter,
    body: archive.body,
    citations: archive.citations,
  });
  return { text, edited: text !== reviewed };
}

