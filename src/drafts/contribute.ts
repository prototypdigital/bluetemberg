/** Write the new item with exclusive create (a skill's dir must be new too) and stage it. */
function writeStaged(git: GitRunner, repo: string, kind: DraftKind, file: string, text: string): void {
  const target = join(repo, ...file.split('/'));
  assertNoSymlinks(repo, target);
  if (kind === 'skill') {
    mkdirSync(dirname(dirname(target)), { recursive: true });
    mkdirSync(dirname(target));
  } else {
    mkdirSync(dirname(target), { recursive: true });
  }
  writeFileSync(target, text, { flag: 'wx' });
  git(['add', '--', file], repo);
}

/**
 * Prepare a contribution branch for promoted draft `name`. Every check runs before the first
 * write; the only writes are the branch switch, the one new file (exclusive create) staged in the
 * packs repo, and the PR body under `.bluetemberg/drafts/promoted/`.
 */
export function prepareContribution(root: string, name: string, opts: ContributeOptions): ContributionResult {
  const marker = agentSessionMarker(opts.env ?? process.env);
  if (marker) {
    throw new Error(
      `draft pr refuses to run inside an agent session (${marker} is set) — it writes to another repository`,
    );
  }
  assertDraftName(name);
  const git = opts.git ?? runGit;
  const repo = resolve(opts.packsRepo);

  const archive = readArchive(root, name);
  const promoted = readPromoted(root, name, archive);
  const { range } = archive;

  assertPacksRepo(git, repo);
  git(['fetch', 'origin', 'main'], repo);
  const tree = packsTree(git, repo);
  const pack = pickPack(git, repo, tree, archive, opts.pack);
  assertNameFree(tree, archive.kind, name);
  const branch = `feat/${archive.kind}-${name}`;
  if (branchExists(git, repo, branch)) throw new Error(`branch ${branch} already exists in the packs repo`);

  const item = packItemPath(pack, archive.kind, name);
  const title = prTitle(archive, name, range);
  const bodyPath = join(promotedDir(root), `${name}.pr.md`);
  assertNoSymlinks(root, bodyPath);

  const previous = git(['branch', '--show-current'], repo).trim();
  git(['switch', '-c', branch, BASE_REF], repo);
  try {
    writeStaged(git, repo, archive.kind, item.file, promoted.text);
  } catch (err) {
    const back = previous ? `git switch ${previous}` : 'git switch -';
    const message = err instanceof Error ? err.message : String(err);
    throw new Error(
      `${message}\nThe packs repo is now on ${branch} with nothing staged; \`${back}\` returns you.`,
    );
  }

  writeFileSync(bodyPath, prBody(archive, pack, promoted.edited, range));
  const bodyFile = displayPath(root, bodyPath);
  return {
    pack,
    branch,
    file: item.file,
    bodyFile,
    title,
    editedAfterReview: promoted.edited,
    nextSteps: nextSteps(repo, branch, title, resolve(bodyPath)),
  };
}
